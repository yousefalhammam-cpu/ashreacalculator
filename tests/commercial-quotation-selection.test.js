'use strict';
const assert=require('assert'),fs=require('fs'),vm=require('vm');
const source=fs.readFileSync(require('path').join(__dirname,'../app.js'),'utf8');
const system={id:'s1',qty:2,selectedBtu:24000,selectedAirflowCfm:800,quotationDraft:{snapshot:{project:{projectName:'Test'},quantity:2,standardCapacityBtuH:24000},lines:[{key:'equipment',quantity:2,unitPrice:3400},{key:'installation',quantity:1,unitPrice:200}],discount:100}};
const options=[{unitCapacityDifferencePct:0,quantity:2,record:{id:'a',manufacturerName:'Example',exactModelNumber:'A',coolingCapacityBtuH:24000,airflowNominalCfm:900}},{unitCapacityDifferencePct:20,record:{id:'b'}}];
let saved=0,rendered=0;
const ctx={window:{AppEquipmentDatabase:{allRecords:()=>options.map(x=>x.record)}},getProjectSystem:()=>system,getSelectedUnitCapacityBtu:s=>s.selectedBtu,isProjectSystemEquipmentRecordCompatible:(_type,r)=>r.equipmentType!=='ahu',getReportScenarioSnapshotForSystem:()=>({requiredCoolingCapacityBtuH:43000,standardUnitCapacityBtuH:99999}),saveProjectSystems:()=>saved++,renderQuote:()=>rendered++};
vm.createContext(ctx);
['getCommercialEquipmentOptions','selectCommercialQuotationEquipment'].forEach(name=>vm.runInContext(source.match(new RegExp('function '+name+'\\([^]*?\\n\\}'))[0],ctx));
assert.strictEqual(ctx.getCommercialEquipmentOptions(system).length,1);
assert.strictEqual(ctx.selectCommercialQuotationEquipment('s1','b'),false);
assert.strictEqual(ctx.selectCommercialQuotationEquipment('s1','a'),true);
assert.strictEqual(system.selectedBtu,24000);
assert.strictEqual(system.selectedAirflowCfm,800);
assert.strictEqual(system.qty,2);
assert.strictEqual(system.quotationDraft.lines[0].unitPrice,3400);
assert.strictEqual(system.quotationDraft.lines[0].quantity,2);
assert.strictEqual(system.quotationDraft.lines[1].unitPrice,200);
assert.strictEqual(system.quotationDraft.discount,100);
assert.strictEqual(system.quotationDraft.snapshot.model,'A');
assert.strictEqual(saved,1);assert.strictEqual(rendered,1);
options[0].record.exactModelNumber='changed';
assert.strictEqual(system.quotationDraft.commercialEquipment.exactModelNumber,'A');
options.push({record:{id:'near',coolingCapacityBtuH:23000}},{record:{id:'undersized',coolingCapacityBtuH:21000}},{record:{id:'wrong-type',equipmentType:'ahu',coolingCapacityBtuH:24000}},{record:{id:'sample',sampleData:true,coolingCapacityBtuH:24000}});
assert.deepStrictEqual(Array.from(ctx.getCommercialEquipmentOptions(system),x=>x.record.id),['a','near']);
system.qty=1;
assert.strictEqual(ctx.getCommercialEquipmentOptions(system).length,0,'must cover required load at actual quantity');
console.log('Commercial selection preserves engineering state and prices.');
vm.runInContext(fs.readFileSync(require('path').join(__dirname,'../data/equipment-records.real.js'),'utf8'),ctx);
ctx.window.AppEquipmentDatabase.allRecords=()=>ctx.window.AirCalcRealEquipmentRecords;
ctx.isProjectSystemEquipmentRecordCompatible=(_type,r)=>r.equipmentType==='package';
ctx.getReportScenarioSnapshotForSystem=()=>({requiredCoolingCapacityBtuH:140000});
system.selectedBtu=150000;system.qty=1;
const makers=Array.from(ctx.getCommercialEquipmentOptions(system),x=>x.record.manufacturerName);
assert(makers.includes('Daikin') && makers.includes('SKM'),'150000 BTU/h quotation should offer multiple catalogue manufacturers when covering the load');
ctx.lang='en';ctx.esc=value=>String(value || '');
vm.runInContext(source.match(/function renderCommercialEquipmentAlternatives\([^]*?\n\}/)[0],ctx);
const cards=ctx.renderCommercialEquipmentAlternatives(system,system.quotationDraft);
assert(cards.includes('Daikin') && cards.includes('SKM'));
assert((cards.match(/<article /g)||[]).length>1,'quote must show multiple available alternatives');
